// Derive the relay-compiler schema from the backend source of truth.
//
// The backend SDL (packages/schema/schema.graphql — canonical in @yanyun/schema,
// also the exact string served as typeDefs by the Worker) declares most root fields in
// `extend type Query` blocks. relay-compiler classifies fields from extension
// blocks as CLIENT extension fields and wraps them in ClientExtension
// artifacts that never reach the network — the root cause of this project's
// recurring "query returns nothing" bugs.
//
// Passing the SDL through buildASTSchema + printSchema merges every extension
// into the base type definitions, producing a semantically identical schema
// (same types, same fields, same nullability) in the canonical merged form the
// compiler expects. Never hand-edit schema.graphql — edit the backend SDL and
// re-run this script.

import { readFileSync, writeFileSync } from 'node:fs';
import { parse, buildASTSchema, printSchema } from 'graphql';

const SRC = new URL('../../packages/schema/schema.graphql', import.meta.url);
const DST = new URL('../schema.graphql', import.meta.url);

const sdl = readFileSync(SRC, 'utf8');
const ast = parse(sdl);
const schema = buildASTSchema(ast);
const printed = printSchema(schema);

const header =
  '# GENERATED by scripts/sync-schema.mjs from ../../packages/schema/schema.graphql (@yanyun/schema canonical).\n' +
  '# Do not edit: extensions are merged into base types on purpose (see script).\n\n';
writeFileSync(DST, header + printed + '\n');
console.log(`schema.graphql synced from backend SDL (${printed.length} bytes)`);
