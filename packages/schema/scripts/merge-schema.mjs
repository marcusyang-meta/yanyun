// Merge the canonical SDL (../schema.graphql) into the canonical printed
// form relay-compiler expects: buildASTSchema + printSchema folds every
// `extend type` block into its base type. Without this, relay-compiler
// treats extension fields as CLIENT extensions and generated artifacts
// never reach the network (this project's recurring "query returns
// nothing" bug).
//
// Usage: node scripts/merge-schema.mjs <output-path>
// Requires the `graphql` package (resolved from the workspace root).
import { readFileSync, writeFileSync } from 'node:fs';
import { parse, buildASTSchema, printSchema } from 'graphql';

const out = process.argv[2];
if (!out) {
  console.error('usage: merge-schema.mjs <output-path>');
  process.exit(1);
}
const sdl = readFileSync(new URL('../schema.graphql', import.meta.url), 'utf8');
const printed = printSchema(buildASTSchema(parse(sdl)));
const header =
  '# GENERATED by @yanyun/schema scripts/merge-schema.mjs from packages/schema/schema.graphql.\n' +
  '# Do not edit: extensions are merged into base types on purpose (see script).\n\n';
writeFileSync(out, header + printed + '\n');
console.log('merged schema ->', out);
