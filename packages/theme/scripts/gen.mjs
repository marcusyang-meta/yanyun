// Generate src/tokens.ts (typed constants) and src/tokens.css (:root vars)
// from src/tokens.json — the single source of design-token data.
// Run: pnpm --filter @yanyun/theme run gen  (or: node scripts/gen.mjs)
import { readFileSync, writeFileSync } from 'node:fs';

const data = JSON.parse(readFileSync(new URL('../src/tokens.json', import.meta.url), 'utf8'));

const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();

const ts = `// GENERATED by scripts/gen.mjs from tokens.json — do not edit by hand.
export const colors = ${JSON.stringify(data.colors, null, 2)} as const;
export const gradients = ${JSON.stringify(data.gradients, null, 2)} as const;
export const fonts = ${JSON.stringify(data.fonts, null, 2)} as const;
export const space = ${JSON.stringify(data.space, null, 2)} as const;
export const radius = ${JSON.stringify(data.radius, null, 2)} as const;
`;
writeFileSync(new URL('../src/tokens.ts', import.meta.url), ts);

let css = '/* GENERATED by scripts/gen.mjs from tokens.json — do not edit by hand. */\n:root {\n';
for (const [k, v] of Object.entries(data.colors)) css += `  --${kebab(k)}: ${v};\n`;
css += `  --card-bg: ${data.gradients.card[0]};\n`;
css += `  --font-sans: ${data.fonts.sansStack};\n`;
css += '}\n';
writeFileSync(new URL('../src/tokens.css', import.meta.url), css);
console.log('tokens.ts + tokens.css generated');
